test('未保存文档保护与键盘弹窗',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'新建项目',exact:true}).click()
  await page.getByLabel('你的点子').fill('草稿保护测试')
  await page.getByRole('button',{name:'保存记录',exact:true}).click()
  await page.getByRole('button',{name:/历史资产回收/}).click()
  await page.getByRole('textbox',{name:'文档正文'}).fill('# 未保存\n不能丢失')
  await page.getByRole('tab',{name:/专家讨论/}).click()
  await expect(page.getByRole('alert')).toContainText('未保存修改')
  await expect(page.getByRole('textbox',{name:'文档正文'})).toHaveValue('# 未保存\n不能丢失')
  await page.getByRole('button',{name:'撤销修改',exact:true}).click()
  await page.getByRole('button',{name:'新建项目',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('tab',{name:'阶段工作',exact:true}).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab',{name:/文档/})).toBeFocused()
})

test('主要页面的自动无障碍检查',async({page})=>{
  const {default:AxeBuilder}=await import('@axe-core/playwright')
  await page.goto('/')
  await expect(page.getByRole('main')).toBeVisible()
  for(const tab of ['阶段工作','文档','专家讨论','证据来源']){
    await page.getByRole('tab',{name:new RegExp('^'+tab)}).click()
    const result=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
    expect(result.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>n.target)}))).toEqual([])
  }
})
